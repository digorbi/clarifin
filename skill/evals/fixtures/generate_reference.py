from __future__ import annotations

from pathlib import Path

import openpyxl
from openpyxl.styles import Alignment, Font, PatternFill

OUTPUT = Path(__file__).parent / "reference.xlsx"

CATEGORIES = [
    ("Groceries", "4CAF50", "supermarket, grocery, lidl, aldi, rewe"),
    ("Dining", "FF9800", "restaurant, cafe, coffee, food delivery"),
    ("Transport", "2196F3", "uber, taxi, train, bvg, db, fuel"),
    ("Utilities", "9C27B0", "electricity, gas, water, internet, phone"),
    ("Health", "F44336", "pharmacy, doctor, gym, fitness"),
    ("Shopping", "795548", "amazon, clothing, electronics"),
    ("Entertainment", "E91E63", "cinema, netflix, spotify, games"),
    ("Transfer", "607D8B", "bank transfer, own account"),
    ("Other", "9E9E9E", ""),
]

# Subset of known joint-account transactions for illustration
SAMPLE = [
    ("Mar 1, 2026", "CafeNord", -4.19, "Dining"),
    ("Mar 1, 2026", "REWE Supermarkt", -34.67, "Groceries"),
    ("Mar 3, 2026", "BVG Monatsticket", -86.00, "Transport"),
    ("Mar 5, 2026", "Transfer from THOMAS MÜLLER", 900.00, "Transfer"),
    ("Mar 7, 2026", "Netflix", -15.99, "Entertainment"),
    ("Mar 10, 2026", "Apotheke Berlin", -12.40, "Health"),
    ("Mar 15, 2026", "Amazon DE", -67.50, "Shopping"),
    ("Mar 20, 2026", "Transfer from THOMAS MÜLLER", 750.00, "Transfer"),
    ("Mar 28, 2026", "Transfer from THOMAS MÜLLER", 250.00, "Transfer"),
]


def _fill(hex_color: str) -> PatternFill:
    return PatternFill("solid", fgColor=hex_color)


def _bold(size: int = 11) -> Font:
    return Font(bold=True, size=size)


def build_monthly(wb: openpyxl.Workbook) -> None:
    ws = wb.create_sheet("2026-03")

    ws.merge_cells("A1:D1")
    ws["A1"].value = "March 2026"
    ws["A1"].font = Font(bold=True, size=14)
    ws["A1"].alignment = Alignment(horizontal="center")

    for col, h in enumerate(["Category", "Income", "Expenses", "Net"], 1):
        cell = ws.cell(row=3, column=col, value=h)
        cell.font = _bold()

    totals: dict[str, list[float]] = {}
    for _, _, amount, cat in SAMPLE:
        inc, exp = totals.get(cat, [0.0, 0.0])
        if amount > 0:
            totals[cat] = [inc + amount, exp]
        else:
            totals[cat] = [inc, exp + abs(amount)]

    r = 4
    for cat, (inc, exp) in sorted(totals.items()):
        ws.cell(row=r, column=1, value=cat)
        if inc:
            ws.cell(row=r, column=2, value=inc)
        if exp:
            ws.cell(row=r, column=3, value=exp)
        ws.cell(row=r, column=4, value=inc - exp)
        r += 1

    total_inc = sum(a for _, _, a, _ in SAMPLE if a > 0)
    total_exp = sum(abs(a) for _, _, a, _ in SAMPLE if a < 0)
    for col, val in enumerate([("Total", total_inc, total_exp, total_inc - total_exp)], 1):
        for i, v in enumerate(val):
            c = ws.cell(row=r + 1, column=i + 1, value=v)
            c.font = _bold()

    header_row = r + 3
    for col, h in enumerate(["Date", "Description", "Amount", "Category"], 1):
        ws.cell(row=header_row, column=col, value=h).font = _bold()

    prev_date = ""
    data_row = header_row + 1
    for date, desc, amount, cat in SAMPLE:
        if date != prev_date:
            ws.cell(row=data_row, column=1, value=date).font = _bold()
            prev_date = date
        ws.cell(row=data_row, column=2, value=desc)
        amt_cell = ws.cell(row=data_row, column=3, value=amount)
        amt_cell.font = Font(color="00AA00" if amount > 0 else "000000")
        ws.cell(row=data_row, column=4, value=cat)
        data_row += 1

    ws.column_dimensions["A"].width = 14
    ws.column_dimensions["B"].width = 42
    ws.column_dimensions["C"].width = 12
    ws.column_dimensions["D"].width = 16


def build_settings(wb: openpyxl.Workbook) -> None:
    ws = wb.create_sheet("Settings")
    for col, h in enumerate(["Category", "Color (hex)", "Keywords"], 1):
        ws.cell(row=1, column=col, value=h).font = _bold()
    for row, (name, color, keywords) in enumerate(CATEGORIES, 2):
        ws.cell(row=row, column=1, value=name)
        c = ws.cell(row=row, column=2, value=f"#{color}")
        c.fill = _fill(color)
        ws.cell(row=row, column=3, value=keywords)
    ws.column_dimensions["A"].width = 16
    ws.column_dimensions["B"].width = 14
    ws.column_dimensions["C"].width = 50


def build_parsers(wb: openpyxl.Workbook) -> None:
    ws = wb.create_sheet("_parsers")
    ws.sheet_state = "hidden"
    rows = [
        ("bank", "Neobank"),
        ("format", "Joint Account EUR Statement"),
        ("version", "1"),
        ("updated", "2026-03-15"),
        ("code", "# full Python parser source stored here"),
        ("---", ""),
    ]
    for r, (k, v) in enumerate(rows, 1):
        ws.cell(row=r, column=1, value=k)
        ws.cell(row=r, column=2, value=v)


def build_hashes(wb: openpyxl.Workbook) -> None:
    ws = wb.create_sheet("_tx_hashes")
    ws.sheet_state = "hidden"
    ws.cell(row=1, column=1, value="# sha256[:16] hashes of processed transactions")
    ws.cell(row=2, column=1, value="a3f1b2c4d5e6f7a8")


def main() -> None:
    wb = openpyxl.Workbook()
    wb.remove(wb.active)
    build_monthly(wb)
    build_settings(wb)
    build_parsers(wb)
    build_hashes(wb)
    wb.save(str(OUTPUT))
    print(f"Written: {OUTPUT}")


if __name__ == "__main__":
    main()
